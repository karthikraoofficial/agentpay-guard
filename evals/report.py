"""The Eval report: the eval run's numbers, committed so each release publishes them.

`run_evals --write-report` writes evals/report.json and the README's eval table from one
run. A full `run_evals` run rebuilds both in memory and fails if either committed copy
differs, so the published numbers always match the golden set and the engine.

Only numbers that every machine reproduces go in: case counts, outcome counts,
false-allow, false-block, wrong reason codes and the step-up rate. Engine latency is
printed by the run, not stored, and latency is gated by the perf tests instead.
"""

import json
import re
from collections.abc import Sequence
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict

REPORT = Path(__file__).resolve().parent / "report.json"
README = Path(__file__).resolve().parents[1] / "README.md"
REGENERATE = "uv run python -m evals.run_evals --write-report"
START = "<!-- eval-report:start -->"
END = "<!-- eval-report:end -->"
NONE = chr(0x2013)  # en dash: this kind of file has no value here
LATENCY_GATE = "`POST /v1/decisions` p95 under 150 ms, gated in CI by the perf tests"


class _Strict(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class OutcomeCounts(_Strict):
    cases: int
    allow: int
    step_up: int
    block: int


class FileEntry(_Strict):
    file: str
    kind: Literal["decision", "dispute", "narrative"]
    # Policy pack the file is decided with; None for the citation checker's file.
    pack: str | None
    cases: int
    mismatches: int
    # Decision files only. Outcome counts are of decision-stage cases; approval-stage
    # cases are labelled with a Consent resolution instead (ADR-0010).
    allow: int | None = None
    step_up: int | None = None
    block: int | None = None
    false_allow: int | None = None
    false_block: int | None = None
    wrong_reason: int | None = None


class EvalReport(_Strict):
    about: str = (
        "Generated by `" + REGENERATE + "`. Do not edit by hand. Decision cases count "
        "every case in the decision files, approval re-checks included; the step-up rate "
        "is over decision-stage cases. Latency: " + LATENCY_GATE + "."
    )
    decision_cases: int
    false_allow: int
    false_block: int
    wrong_reason: int
    mismatches: int
    step_up_rate: float
    files: list[FileEntry]
    scenarios: dict[str, OutcomeCounts]


def build(files: Sequence[FileEntry], scenarios: dict[str, OutcomeCounts]) -> EvalReport:
    decision = [f for f in files if f.kind == "decision"]
    decided = sum((f.allow or 0) + (f.step_up or 0) + (f.block or 0) for f in decision)
    step_ups = sum(f.step_up or 0 for f in decision)
    return EvalReport(
        decision_cases=sum(f.cases for f in decision),
        false_allow=sum(f.false_allow or 0 for f in decision),
        false_block=sum(f.false_block or 0 for f in decision),
        wrong_reason=sum(f.wrong_reason or 0 for f in decision),
        mismatches=sum(f.mismatches for f in files),
        step_up_rate=round(step_ups / decided, 4) if decided else 0.0,
        files=list(files),
        scenarios=dict(sorted(scenarios.items())),
    )


def to_json(report: EvalReport) -> str:
    return json.dumps(report.model_dump(mode="json"), indent=2) + "\n"


def _cell(value: int | None) -> str:
    return NONE if value is None else str(value)


def table(report: EvalReport) -> str:
    """The README's eval table, in Markdown."""
    lines = [
        f"**{report.decision_cases} labelled Decision cases.** "
        f"False-allow {report.false_allow}, false-block {report.false_block}, "
        f"wrong Reason code {report.wrong_reason}. "
        f"Step-up rate {report.step_up_rate:.1%} of decision-stage cases. "
        f"Latency: {LATENCY_GATE}.",
        "",
        "| File | Pack | Cases | Allow | Step-up | Block | False-allow | False-block "
        "| Wrong reason | Mismatches |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for f in report.files:
        lines.append(
            f"| `{f.file}` | {f.pack or NONE} | {f.cases} | {_cell(f.allow)} "
            f"| {_cell(f.step_up)} | {_cell(f.block)} | {_cell(f.false_allow)} "
            f"| {_cell(f.false_block)} | {_cell(f.wrong_reason)} | {f.mismatches} |"
        )
    if report.scenarios:
        lines += [
            "",
            "| Scenario | Cases | Allow | Step-up | Block |",
            "| --- | ---: | ---: | ---: | ---: |",
        ]
        for name, c in report.scenarios.items():
            lines.append(f"| {name} | {c.cases} | {c.allow} | {c.step_up} | {c.block} |")
    lines.append("")
    lines.append(
        "Allow, step-up and block count decision-stage cases; approval re-checks are "
        f"labelled with a Consent resolution instead, so they show {NONE}. "
        f"Generated by `{REGENERATE}`; CI fails if it is out of date."
    )
    return "\n".join(lines)


_BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)


def _with_table(readme: str, report: EvalReport) -> str:
    if not _BLOCK.search(readme):
        raise ValueError(f"README has no {START} … {END} block for the eval table")
    block = f"{START}\n{table(report)}\n{END}"
    return _BLOCK.sub(lambda _: block, readme, count=1)


def _read(path: Path) -> str:
    # Git on Windows may check files out with CRLF; compare content, not line endings.
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""


def write(report: EvalReport, report_path: Path, readme_path: Path) -> None:
    readme = _with_table(_read(readme_path), report)
    report_path.write_text(to_json(report), encoding="utf-8", newline="\n")
    readme_path.write_text(readme, encoding="utf-8", newline="\n")


def stale(report: EvalReport, report_path: Path, readme_path: Path) -> list[str]:
    """Which committed copies differ from this run; empty when both are current."""
    out: list[str] = []
    if _read(report_path) != to_json(report):
        out.append(str(report_path))
    readme = _read(readme_path)
    try:
        current = _with_table(readme, report) == readme
    except ValueError:
        current = False
    if not current:
        out.append(f"{readme_path} (eval table)")
    return out
